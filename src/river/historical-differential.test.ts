import { describe, expect, test } from 'bun:test'
import { writeFileSync } from 'node:fs'
import { SiteNode, type SiteNode as SiteNodeType } from '@pascal-app/core'
import {
  EARLIER_CARVES_FIXTURE,
  FIRST_FINGERPRINT_COMMIT,
  PRE_V3_COMMIT,
  preV3Cases,
  readEarlierCarveFixtures,
  savedSiteCases,
  type EarlierCarveFixtures,
} from './earlier-carves'
import { extractSourceAt, type HistoricalSource } from './historical-source'

/**
 * Opt-in: rebuilds `fixtures/earlier-carves.json` with the real carvers of
 * earlier commits, extracted from git, and checks the vendored file against
 * them (`RIVER_HISTORICAL=check`), or rewrites it (`RIVER_HISTORICAL=write`).
 * It needs those commits in git history, so it never runs by default: the
 * acceptance tests read the vendored file and need no history at all.
 */
const mode = process.env.RIVER_HISTORICAL

type EarlierCarver = Readonly<{
  parseRiver: (raw: unknown) => Record<string, unknown>
  carve: (
    site: SiteNodeType,
    rivers: readonly unknown[],
  ) => { terrainData: SiteNodeType['terrain']; metadata: SiteNodeType['metadata'] }
}>

async function loadCarver(source: HistoricalSource): Promise<EarlierCarver> {
  const terrainModule = (await source.load('src/river/terrain.ts')) as {
    rebuildRiverTerrain: EarlierCarver['carve']
  }
  const schemaModule = (await source.load('src/river/schema.ts')) as {
    RiverNode: { parse: EarlierCarver['parseRiver'] }
  }
  return {
    parseRiver: (raw) => schemaModule.RiverNode.parse(raw),
    carve: terrainModule.rebuildRiverTerrain,
  }
}

async function withCarverAt<Result>(
  commit: string,
  run: (carver: EarlierCarver) => Result,
): Promise<Result> {
  const source = extractSourceAt(commit)
  try {
    return run(await loadCarver(source))
  } finally {
    source.dispose()
  }
}

async function buildEarlierCarveFixtures(): Promise<EarlierCarveFixtures> {
  const preV3Carves = await withCarverAt(PRE_V3_COMMIT, (carver) =>
    Object.fromEntries(
      Object.entries(preV3Cases()).map(([name, { site, rivers }]) => {
        const saved = rivers.map((raw) => carver.parseRiver(raw))
        return [name, { site, rivers: saved, carvedTerrain: carver.carve(site, saved).terrainData }]
      }),
    ),
  )
  const savedSites = await withCarverAt(FIRST_FINGERPRINT_COMMIT, (carver) =>
    Object.fromEntries(
      Object.entries(savedSiteCases()).map(([name, { site, rivers }]) => {
        const saved = rivers.map((raw) => carver.parseRiver(raw))
        const carved = carver.carve(site, saved)
        const savedSite = SiteNode.parse({ ...site, terrain: carved.terrainData, metadata: carved.metadata })
        return [name, { site: savedSite, rivers: saved }]
      }),
    ),
  )
  const fixtures = {
    provenance:
      `preV3Carves: inputs carved by the river carver at ${PRE_V3_COMMIT}. savedSites: Sites ` +
      `carved and stamped by the carver at ${FIRST_FINGERPRINT_COMMIT}. Generated by ` +
      'RIVER_HISTORICAL=write bun test src/river/historical-differential.test.ts from the ' +
      'cases in earlier-carves.ts; do not edit by hand.',
    preV3Carves,
    savedSites,
  }
  return JSON.parse(JSON.stringify(fixtures)) as EarlierCarveFixtures
}

describe.if(mode === 'check' || mode === 'write')('fixtures from earlier carvers in git history', () => {
  test('earlier-carves.json is exactly what the earlier carvers produce', async () => {
    const fixtures = await buildEarlierCarveFixtures()
    if (mode === 'write') writeFileSync(EARLIER_CARVES_FIXTURE, `${JSON.stringify(fixtures, null, 1)}\n`)
    expect(readEarlierCarveFixtures()).toEqual(fixtures)
  })
})
